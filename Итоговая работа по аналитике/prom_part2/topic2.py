from scipy.stats import norm

# Параметры
p1 = 0.05              # Текущая конверсия
delta_p = 0.002        # Ожидаемый прирост
p2 = p1 + delta_p      # Конверсия в тестовой группе
alpha = 0.03           # Альфа-уровень для доверия 97%
beta = 0.13            # Бета-уровень для мощности 87%

# Z-значения для alpha и beta
Z_alpha = norm.ppf(1 - alpha / 2)
Z_beta = norm.ppf(1 - beta)

# Расчет необходимой выборки для каждой группы
n = ((Z_alpha * (2 * p1 * (1 - p1))**0.5 + Z_beta * ((p1 * (1 - p1) + p2 * (1 - p2))**0.5))**2) / (delta_p**2)
n = int(n)  # Округление до целого числа

# Общее количество пользователей для теста с 3 источниками трафика
total_users = 3 * n

# Среднее число пользователей в день (из 40,000 в месяц)
users_per_day = 40000 / 30

# Количество дней для тестирования
days_required = total_users / users_per_day

print(f"Необходимый размер выборки для каждой группы: {n} пользователей")
print(f"Общее количество пользователей для теста: {total_users}")
print(f"Необходимое количество дней для тестирования: {days_required:.2f} дней")

