
conversions = [25000, 30000, 32000]
visitors = [40000, 40000, 40000]  # Общее количество посетителей для каждого источника
alpha = 0.03  # Уровень значимости (97% доверие)
# Рассчитаем конверсию для каждого источника
# conversion_rates = [conv / visitors for conv in conversions]

# Подсчет конверсии для каждого источника
p1 = conversions[0] / visitors[0]
p2 = conversions[1] / visitors[1]
p3 = conversions[2] / visitors[2]

print(f"Источник 1: {p1 * 100:.1f}% ({conversions[0]} конверсий).")
print(f"Источник 2: {p2 * 100:.1f}% ({conversions[1]} конверсий).")
print(f"Источник 3: {p3 * 100:.1f}% ({conversions[2]} конверсий).")
print("\nЭти конверсии значительно выше текущей базовой конверсии в 5%. Проверим статистическую значимость различий.")


from scipy.stats import norm
def calculate_z_p(p1, p2, n1, n2):
    pooled_p = (p1 * n1 + p2 * n2) / (n1 + n2)  # Объединенная вероятность успеха
    se = (pooled_p * (1 - pooled_p) * (1 / n1 + 1 / n2)) ** 0.5  # Стандартная ошибка
    z_stat = (p1 - p2) / se
    p_value = 2 * (1 - norm.cdf(abs(z_stat)))  # Двустороннее p-значение
    return z_stat, p_value

# Размер выборки для каждого источника
# conversions = [25000, 30000, 32000]
n1, n2, n3 = visitors


# Расчет Z-статистики и p-значений между источниками
z_stat_1_vs_2, p_value_1_vs_2 = calculate_z_p(p1, p2, n1, n2)
z_stat_2_vs_3, p_value_2_vs_3 = calculate_z_p(p2, p3, n2, n3)

# Вывод результатов
print("\nРезультаты статистического анализа:")
print(f"Сравнение источников 1 и 2:\n    Z-статистика: {z_stat_1_vs_2:.2f}\n    P-значение: {p_value_1_vs_2:.4f}")
print(f"Сравнение источников 2 и 3:\n    Z-статистика: {z_stat_2_vs_3:.2f}\n    P-значение: {p_value_2_vs_3:.4f}")



# Заключение на основе p-значений
if p_value_1_vs_2 < alpha:
    print("\nРазличие между источником 1 и источником 2 статистически значимо.")
else:
    print("\nРазличие между источником 1 и источником 2 НЕ статистически значимо.")

if p_value_2_vs_3 < alpha:
    print("Различие между источником 2 и источником 3 статистически значимо.")
else:
    print("Различие между источником 2 и источником 3 НЕ статистически значимо.")

